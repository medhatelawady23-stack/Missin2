class Command(BaseCommand):
    help = 'Seeds all 6 official work types, elements, and activities for locations'

    def handle(self, *args, **options):
        self.stdout.write(self.style.SUCCESS('Starting seeding of work hierarchy...'))
        
        created_wt_count = 0
        created_elem_count = 0
        created_act_count = 0

        for wt_data in DATA:
            wt_name = wt_data['name']
            wt_category = wt_data['category']

            work_type, wt_created = WorkType.objects.get_or_create(
                name=wt_name,
                defaults={'category': wt_category, 'is_active': True}
            )
            if not wt_created:
                work_type.category = wt_category
                work_type.is_active = True
                work_type.save()
            else:
                created_wt_count += 1

            for elem_data in wt_data['elements']:
                elem_name = elem_data['name']
                element, elem_created = WorkItemDetail.objects.get_or_create(
                    work_type=work_type,
                    name=elem_name,
                    defaults={'is_active': True}
                )
                if elem_created:
                    created_elem_count += 1

                for act_name in elem_data['activities']:
                    activity, act_created = WorkActivity.objects.get_or_create(
                        element=element,
                        name=act_name,
                        defaults={'is_active': True}
                    )
                    if act_created:
                        created_act_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'Seeding completed successfully! WorkTypes: {created_wt_count}, Elements: {created_elem_count}, Activities: {created_act_count}'
        ))
